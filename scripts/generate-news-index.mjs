import fs from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const newsDir = path.join(root, 'content', 'news');
const output = path.join(root, 'src', 'lib', 'news', 'generated.js');

const files = (await fs.readdir(newsDir))
  .filter((name) => name.endsWith('.json'))
  .sort();

if (files.length === 0) {
  throw new Error('No news JSON files found in content/news');
}

const imports = [];
const rows = [];

for (let i = 0; i < files.length; i += 1) {
  const file = files[i];
  const varName = `news${i}`;
  const slug = file.replace(/\.json$/i, '');

  imports.push(`import ${varName} from '../../../content/news/${file}' with { type: 'json' };`);
  rows.push(`  { slug: ${JSON.stringify(slug)}, entry: ${varName} }`);
}

const source = `// AUTO-GENERATED by scripts/generate-news-index.mjs
// Do not edit manually.

${imports.join('\n')}

export const generatedNews = [
${rows.join(',\n')}
];

export const generatedNewsSlugs = generatedNews.map((item) => item.slug);
`;

await fs.writeFile(output, source, 'utf8');
console.log(`Generated ${files.length} news entries -> ${path.relative(root, output)}`);
